TITLE_KEYWORDS = {
    "Anime & Manga": ["yu-gi-oh", "yu gi oh", "yugioh", "yu yu hakusho", "dna2", "dna 2", "lupin the 3rd", "lupin iii"],
    "Adult": ["playboy", "sex", "erotic", "porn", "lust", "vinyl dolls", "penthouse", "sensual", "orgasm", "nude", "showgirl", "hyper police"],
}
SPECIAL_MAP = {"Westerns": "Classics", "Cult Movies": "Horror"}

def _clean_segments(cat_line):
    segs = [s for s in cat_line.strip().split("|") if s]
    return [s.rsplit("[", 1)[0].strip() for s in segs]

def _paths_from_category_lines(category_lines):
    paths = []
    for raw in (category_lines or []):
        if not raw.strip().startswith("|"):
            continue
        names = _clean_segments(raw)
        if "Genres" in names:
            paths.append(" > ".join(names))
    return paths

def infer_genre(category_lines, title):
    counter = Counter()
    for raw in (category_lines or []):
        if not raw.strip().startswith("|"):
            continue
        names = _clean_segments(raw)
        if "Genres" not in names:
            continue
        idx = names.index("Genres")
        if idx + 1 >= len(names):
            continue

        first = names[idx + 1]
        cand = names[idx + 2] if (first == "Special Interests" and idx + 2 < len(names)) else first
        cand = SPECIAL_MAP.get(cand, cand)

        w = 2 if "General" in names[idx + 1:] else 1
        counter[cand] += w

    if len(counter) > 1:
        for ex in list(EXCLUDED_IF_OTHERS):
            if ex in counter and len(counter) > 1:
                del counter[ex]

    if counter:
        return counter.most_common(1)[0][0]

    t = (title or "").lower()
    for key, g in TITLE_FORCE_MAP:
        if key in t:
            return g
    for g, kws in TITLE_KEYWORDS.items():
        if any(k in t for k in kws):
            return g
    return "UNCATEGORIZED"

