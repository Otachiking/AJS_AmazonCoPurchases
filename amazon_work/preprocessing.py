product_meta = {}

with open(META_PATH, "r", encoding="latin-1") as f:
    current = {}
    cat_lines_remaining = 0

    def finalize_current(cur):
        if not cur or "Id" not in cur:
            return
        pid = cur["Id"]
        product_meta[pid] = {
            "title": cur.get("title", "").strip(),
            "group": cur.get("group", "").strip(),
            "category_lines": cur.get("category_lines", []),
        }

    for raw in f:
        line = raw.rstrip("\n")

        if not line.strip():
            finalize_current(current)
            current = {}
            cat_lines_remaining = 0
            continue

        striped = line.strip()

        if striped.startswith("Id:"):
            try:
                current["Id"] = int(striped.split("Id:")[1].strip())
            except ValueError:
                pass
        elif striped.startswith("title:"):
            current["title"] = striped.split("title:")[1].strip()
        elif striped.startswith("group:"):
            current["group"] = striped.split("group:")[1].strip()
        elif striped.startswith("categories:"):
            parts = striped.split()
            if len(parts) >= 2:
                try:
                    cat_lines_remaining = int(parts[1])
                except ValueError:
                    cat_lines_remaining = 0
            current.setdefault("category_lines", [])
        elif striped.startswith("|") and cat_lines_remaining > 0:
            current.setdefault("category_lines", []).append(line)
            cat_lines_remaining -= 1

    finalize_current(current)

